"""
你的理解（不正确）
------------------
"s1=s1*s2, s1*=s3, ..."

这暗示了累积乘法，但这不是 Flash Attention 的做法。

正确的理解
----------
Flash Attention 使用的是带缩放的累积加法：

对于每个新块：
    α = exp(m_old - m_new)    # 校正因子（不是累积乘积！）

    l_new = α * l_old + contribution_new    # 缩放后的加法
    acc_new = α * acc_old + contribution_new # 缩放后的加法

α 因子不是累积乘积，而是一个重新缩放因子：
    - 对每个块重新计算
    - 仅依赖于 old_max 和 new_max（不依赖于之前的 α 值）
    - 当新的最大值更大时，用于缩小旧的贡献

为什么这样行得通？
------------------
考虑：softmax([a, b, c]) = softmax(softmax([a, b]) 与 [c] 合并)

数学恒等式：
    exp(a - m_new) = exp(a - m_old) × exp(m_old - m_new)
                              ↑                ↑
                         旧的贡献          校正因子

所以我们可以增量式地合并结果，而不需要存储所有值。
"""

# ═══════════════════════════════════════════════════════════════════════════════
# 第五部分：长序列的 Split-KV 技术
# ═══════════════════════════════════════════════════════════════════════════════

"""
对于非常长的序列（>8K 个 token），单个线程处理所有 KV token 会成为瓶颈。
Split-KV 在 KV 维度上进行并行化。

阶段一：并行部分计算
--------------------
将 KV 分成 S 个块，每个线程处理一个块：

    线程 1: KV[0 : N/S]       → (o₁, m₁, l₁)
    线程 2: KV[N/S : 2N/S]    → (o₂, m₂, l₂)
    ...
    线程 S: KV[(S-1)N/S : N]  → (oₛ, mₛ, lₛ)

注意：oᵢ 已经是归一化的：oᵢ = Σ exp(S - mᵢ) * V / lᵢ

阶段二：归约合并
----------------
使用相同的在线 softmax 原理合并部分结果！

    m_global = max(m₁, m₂, ..., mₛ)
    l_global = Σᵢ exp(mᵢ - m_global) × lᵢ
    o_global = Σᵢ exp(mᵢ - m_global) × lᵢ × oᵢ

    output = o_global / l_global

关键洞见：每个部分输出 oᵢ 已经除以了 lᵢ，所以我们在合并时需要
先乘回去，然后除以 l_global 重新归一化。
"""

